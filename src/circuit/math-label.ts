/**
 * High-fidelity vector LaTeX math rendering for schematic component labels and values.
 *
 * Uses Obsidian's built-in `renderMath` (MathJax) when available to produce crisp,
 * vector-compatible SVG glyphs that persist in notebook canvas rendering and PDF export.
 *
 * Features a pure vector SVG fallback with subscript/superscript `<tspan>` and Greek
 * character symbol support for testing and offline environments.
 */

export interface MathLabelOptions {
  fontSize?: number;
  color?: string;
  anchor?: "start" | "middle" | "end";
  fontWeight?: string | number;
  extraAttributes?: string;
}

const GREEK_SYMBOLS: Record<string, string> = {
  "\\alpha": "α",
  "\\beta": "β",
  "\\gamma": "γ",
  "\\Gamma": "Γ",
  "\\delta": "δ",
  "\\Delta": "Δ",
  "\\epsilon": "ε",
  "\\theta": "θ",
  "\\lambda": "λ",
  "\\mu": "μ",
  "\\pi": "π",
  "\\sigma": "σ",
  "\\tau": "τ",
  "\\phi": "φ",
  "\\omega": "ω",
  "\\Omega": "Ω",
  "\\infty": "∞",
  "\\pm": "±",
  "\\mp": "∓",
  "\\neq": "≠",
  "\\approx": "≈",
  "\\leq": "≤",
  "\\geq": "≥",
  "\\angle": "∠",
  "\\degree": "°",
};

/** Checks whether a string contains LaTeX math syntax */
export function isLatexMath(text: string): boolean {
  if (!text) return false;
  const trimmed = text.trim();
  if (trimmed.startsWith("$") && trimmed.endsWith("$") && trimmed.length > 2) return true;
  return /[_^\\{}]/.test(text);
}

/** Strips leading and trailing math mode delimiters ($ ... $) */
export function stripMathDelimiters(text: string): string {
  const trimmed = text.trim();
  if (trimmed.startsWith("$") && trimmed.endsWith("$") && trimmed.length >= 2) {
    return trimmed.slice(1, -1).trim();
  }
  return trimmed;
}

// In-memory cache for rendered SVG math snippets
const MATH_SVG_CACHE = new Map<string, string>();

/**
 * Attempts to render math using Obsidian's built-in MathJax engine.
 * Returns inner SVG content and dimensions if successful.
 */
function tryRenderWithObsidianMathJax(
  source: string,
  fontSize: number,
  color: string,
): { svgContent: string; width: number; height: number; yOffset: number } | null {
  try {
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const obsidian = require("obsidian");
    if (typeof obsidian.renderMath !== "function") return null;

    const el = obsidian.renderMath(source, false);
    if (typeof obsidian.finishRenderMath === "function") {
      obsidian.finishRenderMath();
    }

    if (!el) return null;

    // Look for SVG generated by MathJax
    const svgEl = el.querySelector("svg");
    if (!svgEl) return null;

    const viewBoxAttr = svgEl.getAttribute("viewBox");
    let vbW = 100;
    let vbH = 100;
    let vbMinY = 0;
    if (viewBoxAttr) {
      const parts = viewBoxAttr.split(/[\s,]+/).map(Number);
      if (parts.length === 4 && !isNaN(parts[2]) && !isNaN(parts[3])) {
        vbMinY = parts[1];
        vbW = parts[2];
        vbH = parts[3];
      }
    }

    // Scale to requested font size (MathJax 1ex is typically ~400-500 units in viewBox)
    const scale = (fontSize * 1.3) / Math.max(1, vbH);
    const targetW = vbW * scale;
    const targetH = vbH * scale;

    // Extract sanitized inner HTML (glyph defs and g elements)
    // using proper DOM/XML manipulation to guarantee unique IDs, valid references,
    // and no duplicate attributes.
    const inner = scopeMathJaxGlyphs(svgEl, "{{SCOPE}}");

    return {
      svgContent: `<g fill="${color}" stroke="${color}" transform="scale(${scale.toFixed(4)})">${inner}</g>`,
      width: targetW,
      height: targetH,
      yOffset: Math.abs(vbMinY) * scale,
    };
  } catch {
    return null;
  }
}

/**
 * Scopes element IDs and glyph references within MathJax SVG markup using proper DOM/XML manipulation.
 *
 * Ensures:
 * 1. All defined element IDs are prefixed with `scopeId`.
 * 2. All `<use>` references (and any elements referencing IDs via `href` or `xlink:href`)
 *    point to the scoped ID.
 * 3. Both modern `href` and legacy `xlink:href` are provided for PDF export compatibility.
 * 4. No duplicate attributes exist (preventing regex collisions between `href` and `xlink:href`).
 * 5. Scripts and inline event handlers (`on*`) are sanitized.
 */
export function scopeMathJaxGlyphs(
  input: Element | string,
  scopeId: string,
): string {
  if (typeof input !== "string") {
    return scopeMathJaxElement(input, scopeId);
  }

  if (typeof DOMParser !== "undefined") {
    try {
      const isSvgTag = /^\s*<svg\b/i.test(input);
      const wrapped = isSvgTag
        ? input
        : `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">${input}</svg>`;
      const doc = new DOMParser().parseFromString(wrapped, "image/svg+xml");
      const parserError = doc.querySelector("parsererror");
      if (!parserError && doc.documentElement) {
        scopeMathJaxElement(doc.documentElement, scopeId);
        return isSvgTag ? doc.documentElement.outerHTML : doc.documentElement.innerHTML;
      }
    } catch {
      // Fall through to XML parser below
    }
  }

  return scopeMathJaxXml(input, scopeId);
}

function scopeMathJaxElement(svgEl: Element, scopeId: string): string {
  // 1. Remove any <script> elements
  const scripts = svgEl.querySelectorAll("script");
  for (let i = 0; i < scripts.length; i++) {
    scripts[i].remove();
  }

  // 2. Remove inline on* event handler attributes
  const allElements = svgEl.querySelectorAll("*");
  for (let i = 0; i < allElements.length; i++) {
    const el = allElements[i];
    const toRemove: string[] = [];
    for (let j = 0; j < el.attributes.length; j++) {
      const attr = el.attributes[j];
      if (attr.name.toLowerCase().startsWith("on")) {
        toRemove.push(attr.name);
      }
    }
    for (const name of toRemove) {
      el.removeAttribute(name);
    }
  }

  // 3. Ensure xmlns:xlink is present if the element is <svg>
  if (svgEl.tagName.toLowerCase() === "svg" && !svgEl.hasAttribute("xmlns:xlink")) {
    svgEl.setAttribute("xmlns:xlink", "http://www.w3.org/1999/xlink");
  }

  // 4. Map all element IDs to scoped IDs
  const idMap = new Map<string, string>();
  const elementsWithId = svgEl.querySelectorAll("[id]");
  for (let i = 0; i < elementsWithId.length; i++) {
    const el = elementsWithId[i];
    const oldId = el.getAttribute("id");
    if (oldId) {
      const newId = `${scopeId}_${oldId}`;
      idMap.set(oldId, newId);
      el.setAttribute("id", newId);
    }
  }

  // 5. Update all glyph references (use elements or anything with href/xlink:href)
  const useElements = svgEl.querySelectorAll("use, [href], [*|href]");
  for (let i = 0; i < useElements.length; i++) {
    const el = useElements[i];
    const href = el.getAttribute("href");
    const xlinkHref = el.getAttribute("xlink:href") || el.getAttributeNS("http://www.w3.org/1999/xlink", "href");

    let refTarget: string | null = null;
    if (href && href.startsWith("#")) {
      refTarget = href.slice(1);
    } else if (xlinkHref && xlinkHref.startsWith("#")) {
      refTarget = xlinkHref.slice(1);
    }

    if (refTarget) {
      const newRef = idMap.has(refTarget) ? idMap.get(refTarget)! : `${scopeId}_${refTarget}`;
      el.setAttribute("href", `#${newRef}`);
      el.setAttribute("xlink:href", `#${newRef}`);
    }
  }

  // 6. Update any url(#id) references in attributes
  for (let i = 0; i < allElements.length; i++) {
    const el = allElements[i];
    for (let j = 0; j < el.attributes.length; j++) {
      const attr = el.attributes[j];
      if (attr.value && attr.value.includes("url(#")) {
        let updatedVal = attr.value;
        for (const [oldId, newId] of idMap.entries()) {
          updatedVal = updatedVal.split(`url(#${oldId})`).join(`url(#${newId})`);
        }
        if (updatedVal !== attr.value) {
          el.setAttribute(attr.name, updatedVal);
        }
      }
    }
  }

  return svgEl.innerHTML;
}

function scopeMathJaxXml(xmlString: string, scopeId: string): string {
  // Strip scripts
  let xml = xmlString.replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "");

  // Tag matcher: captures (fullTag, isClosing, tagName, attrString, isSelfClosing)
  const tagRegex = /<!--[\s\S]*?-->|<(\/?)([a-zA-Z0-9:_-]+)((?:\s+[^\s=/>]+(?:\s*=\s*(?:"[^"]*"|\x27[^\x27]*\x27|[^\s/>]+))?)*)\s*(\/?)>/g;

  // Pass 1: Collect IDs
  const idMap = new Map<string, string>();
  let tagMatch: RegExpExecArray | null;
  while ((tagMatch = tagRegex.exec(xml)) !== null) {
    const [fullTag, isClosing, , attrString] = tagMatch;
    if (fullTag.startsWith("<!--") || isClosing || !attrString) continue;

    const attrRegex = /([^\s=/>]+)(?:\s*=\s*(?:"([^"]*)"|\x27([^\x27]*)\x27|([^\s/>]+)))?/g;
    let aMatch: RegExpExecArray | null;
    while ((aMatch = attrRegex.exec(attrString)) !== null) {
      if (aMatch[1] === "id") {
        const idVal = aMatch[2] ?? aMatch[3] ?? aMatch[4];
        if (idVal && !idMap.has(idVal)) {
          idMap.set(idVal, `${scopeId}_${idVal}`);
        }
      }
    }
  }

  // Pass 2: Reconstruct tags with scoped IDs and references
  return xml.replace(tagRegex, (fullTag, isClosing, tagName, attrString, isSelfClosing) => {
    if (fullTag.startsWith("<!--")) return fullTag;
    if (isClosing) return `</${tagName}>`;

    const attrs = new Map<string, string>();
    if (attrString) {
      const attrRegex = /([^\s=/>]+)(?:\s*=\s*(?:"([^"]*)"|\x27([^\x27]*)\x27|([^\s/>]+)))?/g;
      let aMatch: RegExpExecArray | null;
      while ((aMatch = attrRegex.exec(attrString)) !== null) {
        const name = aMatch[1];
        const val = aMatch[2] ?? aMatch[3] ?? aMatch[4] ?? "";
        if (!name.toLowerCase().startsWith("on")) {
          attrs.set(name, val);
        }
      }
    }

    if (tagName.toLowerCase() === "svg") {
      if (!attrs.has("xmlns:xlink")) {
        attrs.set("xmlns:xlink", "http://www.w3.org/1999/xlink");
      }
    }

    if (attrs.has("id")) {
      const oldId = attrs.get("id")!;
      attrs.set("id", idMap.get(oldId) ?? `${scopeId}_${oldId}`);
    }

    let refTarget: string | null = null;
    if (attrs.has("href") && attrs.get("href")!.startsWith("#")) {
      refTarget = attrs.get("href")!.slice(1);
    } else if (attrs.has("xlink:href") && attrs.get("xlink:href")!.startsWith("#")) {
      refTarget = attrs.get("xlink:href")!.slice(1);
    }

    if (refTarget) {
      const newRef = idMap.has(refTarget) ? idMap.get(refTarget)! : `${scopeId}_${refTarget}`;
      attrs.set("href", `#${newRef}`);
      attrs.set("xlink:href", `#${newRef}`);
    }

    for (const [name, val] of attrs.entries()) {
      if (val && val.includes("url(#")) {
        let updatedVal = val;
        for (const [oldId, newId] of idMap.entries()) {
          updatedVal = updatedVal.split(`url(#${oldId})`).join(`url(#${newId})`);
        }
        attrs.set(name, updatedVal);
      }
    }

    let res = `<${tagName}`;
    for (const [k, v] of attrs) {
      const escapedVal = v.replace(/"/g, "&quot;");
      res += ` ${k}="${escapedVal}"`;
    }
    return res + (isSelfClosing ? " />" : ">");
  });
}

/**
 * Parses LaTeX sub/superscripts and Greek symbols into vector SVG text with `<tspan>`.
 * Raw text is safely escaped for XML before formatting tags are added.
 */
export function formatSvgTextFallback(source: string): string {
  let text = stripMathDelimiters(source);

  // 1. Safely escape raw text for XML first
  text = escapeXml(text);

  // 2. Replace common Greek macros with Unicode glyphs
  text = text.replace(/\\[a-zA-Z]+/g, (command) => GREEK_SYMBOLS[command] ?? command);

  // 3. Simple fraction fallback: \frac{A}{B} -> A/B
  text = text.replace(/\\frac\{([^{}]+)\}\{([^{}]+)\}/g, "$1/$2");
  text = text.replace(/\\(?:text|mathrm)\{([^{}]+)\}/g, "$1");
  text = text.replace(/\\[,;:!]/g, " ").replace(/\\times/g, "×").replace(/\\cdot/g, "·");

  // 4. Handle subscripts X_{abc} or X_a
  text = text.replace(/_\{([^{}]+)\}/g, '<tspan baseline-shift="sub" font-size="0.75em">$1</tspan>');
  text = text.replace(/_([a-zA-Z0-9])/g, '<tspan baseline-shift="sub" font-size="0.75em">$1</tspan>');

  // 5. Handle superscripts X^{abc} or X^a
  text = text.replace(/\^\{([^{}]+)\}/g, '<tspan baseline-shift="super" font-size="0.75em">$1</tspan>');
  text = text.replace(/\^([a-zA-Z0-9])/g, '<tspan baseline-shift="super" font-size="0.75em">$1</tspan>');

  return text;
}

/**
 * Renders a label containing LaTeX expressions or plain text to an SVG element string.
 */
export function renderLatexLabelToSvg(
  source: string,
  x: number,
  y: number,
  options: MathLabelOptions = {},
): string {
  if (!source) return "";

  const fontSize = options.fontSize || 12;
  const color = options.color || "#0f172a";
  const anchor = options.anchor || "middle";
  const fontWeight = options.fontWeight || "600";
  const extraAttr = options.extraAttributes ? ` ${options.extraAttributes}` : "";

  const cleanSource = stripMathDelimiters(source);
  const cacheKey = `${cleanSource}:${fontSize}:${color}:${anchor}:${fontWeight}:${extraAttr}`;
  const scopeId = `mjx_${Math.random().toString(36).slice(2, 8)}`;

  if (MATH_SVG_CACHE.has(cacheKey)) {
    const cached = MATH_SVG_CACHE.get(cacheKey)!;
    return cached
      .replace(/\{\{X\}\}/g, String(x))
      .replace(/\{\{Y\}\}/g, String(y))
      .replace(/\{\{SCOPE\}\}/g, scopeId);
  }

  // If text doesn't contain math, render plain SVG text
  if (!isLatexMath(source)) {
    const svg = `<text x="{{X}}" y="{{Y}}" font-size="${fontSize}" font-weight="${fontWeight}" fill="${color}" text-anchor="${anchor}"${extraAttr}>${escapeXml(cleanSource)}</text>`;
    MATH_SVG_CACHE.set(cacheKey, svg);
    return svg
      .replace(/\{\{X\}\}/g, String(x))
      .replace(/\{\{Y\}\}/g, String(y))
      .replace(/\{\{SCOPE\}\}/g, scopeId);
  }

  // Attempt MathJax rendering if Obsidian environment is active
  const mathResult = tryRenderWithObsidianMathJax(cleanSource, fontSize, color);
  if (mathResult) {
    let offsetX = 0;
    if (anchor === "middle") offsetX = -mathResult.width / 2;
    else if (anchor === "end") offsetX = -mathResult.width;

    const template = `<g transform="translate({{X}}, {{Y}})"${extraAttr} data-latex-source="${escapeXml(cleanSource)}" xmlns:xlink="http://www.w3.org/1999/xlink">` +
      `<g transform="translate(${offsetX.toFixed(2)}, ${(-mathResult.yOffset / 2).toFixed(2)})">` +
      mathResult.svgContent +
      `</g></g>`;

    MATH_SVG_CACHE.set(cacheKey, template);
    return template
      .replace(/\{\{X\}\}/g, String(x))
      .replace(/\{\{Y\}\}/g, String(y))
      .replace(/\{\{SCOPE\}\}/g, scopeId);
  }

  // Fallback vector SVG with `<tspan>`
  const formatted = formatSvgTextFallback(source);
  const svgFallback = `<text x="{{X}}" y="{{Y}}" font-size="${fontSize}" font-weight="${fontWeight}" fill="${color}" text-anchor="${anchor}"${extraAttr} data-latex-source="${escapeXml(cleanSource)}">${formatted}</text>`;

  // Do not cache a limited fallback: MathJax may become ready on a later render.
  return svgFallback
    .replace(/\{\{X\}\}/g, String(x))
    .replace(/\{\{Y\}\}/g, String(y))
    .replace(/\{\{SCOPE\}\}/g, scopeId);
}

function escapeXml(unsafe: string): string {
  return unsafe
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}
